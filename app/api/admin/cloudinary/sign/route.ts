
import cloudinary from "@/lib/cloudinary";
import { NextResponse } from "next/server";

export const runtime = "nodejs";

const CLOUDINARY_API_SECRET =
  process.env.CLOUDINARY_API_SECRET;

const ALLOWED_FOLDERS = new Set([
  "car-battery-service/settings/logo",
  "car-battery-service/settings/og",
]);

const MAX_TIMESTAMP_AGE_SECONDS = 10 * 60;

export async function POST(request: Request) {
  try {
    if (!CLOUDINARY_API_SECRET) {
      console.error("Cloudinary API secret is missing.");

      return NextResponse.json(
        {
          success: false,
          message: "Upload service is not configured.",
        },
        { status: 500 }
      );
    }

    const body = await request.json();

    const paramsToSign = body?.paramsToSign;

    if (
      !paramsToSign ||
      typeof paramsToSign !== "object" ||
      Array.isArray(paramsToSign)
    ) {
      return NextResponse.json(
        {
          success: false,
          message: "Invalid signature parameters.",
        },
        { status: 400 }
      );
    }

    const folder = paramsToSign.folder;

    if (
      typeof folder !== "string" ||
      !ALLOWED_FOLDERS.has(folder)
    ) {
      return NextResponse.json(
        {
          success: false,
          message: "Invalid upload folder.",
        },
        { status: 400 }
      );
    }

    const timestamp = Number(paramsToSign.timestamp);

    if (
      !Number.isInteger(timestamp) ||
      Math.abs(
        Math.floor(Date.now() / 1000) - timestamp
      ) > MAX_TIMESTAMP_AGE_SECONDS
    ) {
      return NextResponse.json(
        {
          success: false,
          message: "Upload signature has expired.",
        },
        { status: 400 }
      );
    }

    // Sign only the parameters generated by Cloudinary's widget.
    const signature =
      cloudinary.utils.api_sign_request(
        paramsToSign,
        CLOUDINARY_API_SECRET
      );

    return NextResponse.json(
      { signature },
      {
        status: 200,
        headers: {
          "Cache-Control": "no-store",
        },
      }
    );
  } catch (error) {
    console.error(
      "Admin Cloudinary signature error:",
      error
    );

    return NextResponse.json(
      {
        success: false,
        message: "Unable to prepare your image upload.",
      },
      {
        status: 500,
        headers: {
          "Cache-Control": "no-store",
        },
      }
    );
  }
}
